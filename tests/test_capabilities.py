"""docs/capabilities.json — emitted, drift-gated, and loud about its curated layer.

Same discipline as the triad (tests/test_contract_triad.py): the document is
regenerated by ``make contract`` from conf.py DEFAULTS, the urls gate
registry, docs/schema.json and the curated docs/capabilities.meta.json, and a
committed copy that differs from a fresh emission is a failure.
"""
import json
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

if sys.version_info[:2] != (3, 12):
    pytest.skip(
        "emitted from a schema.json pinned to Python 3.12 (see test_contract_triad)",
        allow_module_level=True,
    )

REPO = Path(__file__).resolve().parent.parent
DOCS = REPO / "docs"


def _emit(out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy(DOCS / "schema.json", out_dir / "schema.json")
    subprocess.run(
        [sys.executable, "-m", "stapel_webhooks._capabilities", "--out", str(out_dir)],
        cwd=str(REPO),
        check=True,
        capture_output=True,
    )


def _doc() -> dict:
    return json.loads((DOCS / "capabilities.json").read_text())


def test_capabilities_is_committed_and_has_no_drift(tmp_path):
    assert (DOCS / "capabilities.json").is_file(), "missing docs/capabilities.json — run `make contract`"
    _emit(tmp_path)
    assert (DOCS / "capabilities.json").read_bytes() == (tmp_path / "capabilities.json").read_bytes(), (
        "docs/capabilities.json drifted — run `make contract` and commit it"
    )


def test_axes_are_the_declared_switches_with_their_shipped_defaults():
    from stapel_webhooks.conf import DEFAULTS

    axes = {a["key"]: a for a in _doc()["axes"]}
    assert list(axes) == ["WATCH_CATALOG", "DISPATCH_MODE", "ALLOW_INSECURE_TARGETS"]
    for key, axis in axes.items():
        assert axis["default"] == DEFAULTS[key]
        assert axis["curated"]["summary"] and axis["curated"]["business_label"]
    assert axes["ALLOW_INSECURE_TARGETS"]["default"] is False


def test_operations_total_matches_the_schema():
    schema = json.loads((DOCS / "schema.json").read_text())
    total = sum(
        1 for ops in schema["paths"].values() for m in ops
        if m in ("get", "post", "put", "patch", "delete")
    )
    assert _doc()["operations_total"] == total


def test_version_matches_the_package():
    import tomllib

    project = tomllib.loads((REPO / "pyproject.toml").read_text())["project"]
    doc = _doc()
    assert (doc["module"], doc["version"]) == (project["name"], project["version"])


def test_curated_layer_out_of_sync_fails_loudly():
    from stapel_tools.capabilities import build_capabilities

    from stapel_webhooks._capabilities import axis_config
    from stapel_webhooks.urls_v1 import GATE_REGISTRY

    defaults, is_axis, axis_group = axis_config()
    meta = json.loads((DOCS / "capabilities.meta.json").read_text())
    schema = json.loads((DOCS / "schema.json").read_text())

    def build(m):
        return build_capabilities(
            module="stapel-webhooks", version="0.0.0", defaults=defaults,
            registry=GATE_REGISTRY, schema=schema, meta=m, is_axis=is_axis,
            axis_group=axis_group, canonical_prefix="/webhooks/api/v1", repo=REPO,
        )

    assert build(json.loads(json.dumps(meta)))["axes"]
    broken = json.loads(json.dumps(meta))
    del broken["axes"]["DISPATCH_MODE"]
    with pytest.raises(SystemExit, match="DISPATCH_MODE"):
        build(broken)
